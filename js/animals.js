export const ANIMAL_BY_ID = Object.fromEntries(
  ANIMALS.map((animal) => [animal.id, animal])
);

export const HERD_SPECIES = ANIMALS.filter((animal) => animal.kind === "herd");
export const FLOCK_SPECIES = ANIMALS.filter((animal) => animal.kind === "flock");
export const CRITTER_SPECIES = ANIMALS.filter(
  (animal) => animal.kind === "critter"
);
export const POND_SPECIES = ANIMALS.filter((animal) => animal.kind === "pond");

export function animalAllowed(animal, environment) {
  return (
    environment === "all" ||
    !environment ||
    animal.themes.includes(environment)
  );
}

export function animalsForTheme(environment) {
  return ANIMALS.filter((animal) => animalAllowed(animal, environment));
}
